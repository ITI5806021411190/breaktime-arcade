/**
 * Generates deterministic, varied differences for a given theme and difficulty tier.
 */
function buildLevelDifferences(
  levelId: number,
  baseObjects: SceneObject[],
  difficulty: Difficulty
): DifferenceMetadata[] {
  const count = difficulty === 'easy' ? 3 : difficulty === 'normal' ? 5 : 7;
  const radius = difficulty === 'easy' ? 9.0 : difficulty === 'normal' ? 7.6 : 6.8;

  const altPalette = [
    '#EC4899',
    '#06B6D4',
    '#8B5CF6',
    '#10B981',
    '#F43F5E',
    '#3B82F6',
    '#F59E0B',
  ];

  const candidateStrategies: Array<(obj: SceneObject, idx: number) => DifferenceMetadata> = [
    // 0: Change primary/secondary color vividly
    (obj, idx) => {
      const nextColor =
        obj.color.toUpperCase() === altPalette[idx % altPalette.length]
          ? '#10B981'
          : altPalette[idx % altPalette.length];
      return {
        id: `L${levelId}-D${idx + 1}`,
        targetObjectId: obj.id,
        type: 'change-color',
        labelTh: `สีของวัตถุเปลี่ยนไป`,
        position: { x: obj.x, y: obj.y },
        hitbox: { x: obj.x, y: obj.y, radius },
        patch: {
          color: nextColor,
          secondaryColor: '#FACC15',
        },
      };
    },
    // 1: Remove object
    (obj, idx) => ({
      id: `L${levelId}-D${idx + 1}`,
      targetObjectId: obj.id,
      type: 'remove-object',
      labelTh: `วัตถุหายไปจากภาพ`,
      position: { x: obj.x, y: obj.y },
      hitbox: { x: obj.x, y: obj.y, radius },
      patch: {},
    }),
    // 2: Change size significantly
    (obj, idx) => ({
      id: `L${levelId}-D${idx + 1}`,
      targetObjectId: obj.id,
      type: 'change-size',
      labelTh: `ขนาดของวัตถุเปลี่ยนไป`,
      position: { x: obj.x, y: obj.y },
      hitbox: { x: obj.x, y: obj.y, radius },
      patch: {
        scale: 1.42,
      },
    }),
    // 3: Move position noticeably
    (obj, idx) => {
      const dx = obj.x > 50 ? -6 : 6;
      const dy = obj.y > 50 ? -5 : 5;
      return {
        id: `L${levelId}-D${idx + 1}`,
        targetObjectId: obj.id,
        type: 'move-position',
        labelTh: `ตำแหน่งขยับเปลี่ยนที่`,
        position: { x: obj.x, y: obj.y },
        hitbox: { x: obj.x, y: obj.y, radius },
        patch: { dx, dy },
      };
    },
    // 4: Change shape / flip orientation
    (obj, idx) => ({
      id: `L${levelId}-D${idx + 1}`,
      targetObjectId: obj.id,
      type: 'change-shape',
      labelTh: `รูปทรงหรือทิศทางเปลี่ยนไป`,
      position: { x: obj.x, y: obj.y },
      hitbox: { x: obj.x, y: obj.y, radius },
      patch: {
        flipX: !obj.flipX,
        rotation: 18,
        color: '#22D3EE',
      },
    }),
    // 5: Replace detail / accent
    (obj, idx) => ({
      id: `L${levelId}-D${idx + 1}`,
      targetObjectId: obj.id,
      type: 'replace-detail',
      labelTh: `ลวดลายรายละเอียดเปลี่ยนไป`,
      position: { x: obj.x, y: obj.y },
      hitbox: { x: obj.x, y: obj.y, radius },
      patch: {
        detail: obj.detail === 'plain' ? 'star' : 'plain',
        secondaryColor: '#F43F5E',
        accentColor: '#38BDF8',
      },
    }),
    // 6: Add extra surprise object in open sky/foreground spot
    (_obj, idx) => {
      const addedX = 33;
      const addedY = 25;
      const addedObj: SceneObject = {
        id: `added-special-${levelId}`,
        type: 'decorative',
        shape: 'balloon-bunch',
        x: addedX,
        y: addedY,
        width: 11,
        height: 15,
        color: '#F43F5E',
        secondaryColor: '#FACC15',
        accentColor: '#38BDF8',
        detail: 'triple',
        layerOrder: 9,
      };
      return {
        id: `L${levelId}-D${idx + 1}`,
        targetObjectId: addedObj.id,
        type: 'add-object',
        labelTh: `มีลูกโป่งปริศนาเพิ่มขึ้นมา`,
        position: { x: addedX, y: addedY },
        hitbox: { x: addedX, y: addedY, radius },
        patch: {
          addedObject: addedObj,
        },
      };
    },
  ];

  // Rotate starting object index by levelId so levels in same theme have different targets
  const rotatedObjects = [...baseObjects];
  const shift = levelId % rotatedObjects.length;
  const orderedObjects = [
    ...rotatedObjects.slice(shift),
    ...rotatedObjects.slice(0, shift),
  ];

  const diffs: DifferenceMetadata[] = [];
  for (let i = 0; i < count; i++) {
    const targetObj = orderedObjects[i % orderedObjects.length];
    const strategy = candidateStrategies[i % candidateStrategies.length];
    diffs.push(strategy(targetObj, i));
  }

  return diffs;
}

